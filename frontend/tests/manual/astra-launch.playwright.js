// Run from the repository root through Playwright CLI run-code; see the verification runbook.
async (page) => {
  const origin = 'http://127.0.0.1:18743';
  async function clearFixtureStorage() {
    if (await page.evaluate(() => location.origin) !== origin) throw new Error('Open the offline fixture before running acceptance');
    const health = await (await page.request.get(origin + '/__qa')).json();
    if (health.fixture !== 'astra-launch-offline/v1') throw new Error('Offline fixture identity was not verified');
    await page.evaluate(expected => {
      if (location.origin !== expected) throw new Error('Fixture origin changed before storage reset');
      localStorage.clear();
    }, origin);
  }
  await clearFixtureStorage();
  const context = page.context();
  const faults = [];
  page.on('pageerror', e => faults.push(String(e)));
  await context.route('**/*', route => {
    if (route.request().url().startsWith(origin + '/')) return route.continue();
    return route.abort();
  });
  await page.request.post(origin + '/__qa/reset', {data: {drop_next: true}});
  await page.reload();
  await page.getByRole('textbox').fill('Offline response-loss acceptance');
  await page.getByRole('button', {name: 'Run research + simulate + forecast →'}).click();
  await page.getByRole('button', {name: 'Check launch', exact: true}).waitFor();
  const locked = await page.getByRole('textbox').isDisabled();
  if (!locked) throw new Error('Unknown response did not lock original inputs');
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('drf_launch_intent_v1')));
  if (!saved || saved.admission !== null) throw new Error('Lost response not retained as unknown');
  const before = await (await page.request.get(origin + '/__qa')).json();
  if (before.requests.filter(r => r.method === 'POST').length !== 1) throw new Error('Unexpected launch POST count');
  await page.reload();
  await page.getByRole('button', {name: 'Copy pipeline id'}).waitFor();
  const recovered = await page.evaluate(() => JSON.parse(localStorage.getItem('drf_launch_intent_v1')));
  if (recovered.intent_id !== saved.intent_id || recovered.admission.pipeline_id !== 'pipe_qa1') throw new Error('Wrong recovered identity');
  const after = await (await page.request.get(origin + '/__qa')).json();
  if (after.requests.filter(r => r.method === 'POST').length !== 1) throw new Error('Reload resubmitted launch');
  await page.screenshot({path: 'output/playwright/astra-launch-recovered.png', fullPage: true});
  const second = await context.newPage();
  second.on('pageerror', e => faults.push(String(e)));
  await second.goto(origin);
  await second.getByRole('button', {name: 'Copy pipeline id'}).waitFor();
  const shared = await second.evaluate(() => JSON.parse(localStorage.getItem('drf_launch_intent_v1')));
  if (shared.intent_id !== saved.intent_id) throw new Error('Second tab changed intent');
  await second.getByRole('button', {name: '＋ New', exact: true}).click();
  await second.getByRole('textbox').fill('Explicit second launch');
  await second.getByRole('button', {name: 'Run research + simulate + forecast →'}).click();
  await second.getByRole('button', {name: 'Copy pipeline id'}).waitFor();
  const newIntent = await second.evaluate(() => JSON.parse(localStorage.getItem('drf_launch_intent_v1')));
  if (newIntent.intent_id === saved.intent_id || newIntent.admission.pipeline_id !== 'pipe_qa2') throw new Error('New did not mint a new intent');
  await page.getByRole('button', {name: '＋ New', exact: true}).click();
  await page.getByText('Another tab has a different current launch. Reload before creating a new one.').waitFor();
  const final = await (await page.request.get(origin + '/__qa')).json();
  if (final.requests.filter(r => r.method === 'POST').length !== 2) throw new Error('Stale tab created extra POST');
  await second.setViewportSize({width: 390, height: 844});
  await second.evaluate(() => scrollTo(0, 0));
  const overflow = await second.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw new Error('Mobile page overflow');
  await second.screenshot({path: 'output/playwright/astra-launch-mobile.png', fullPage: true});
  if (faults.length) throw new Error(JSON.stringify(faults));
  await second.close();
  await clearFixtureStorage();
  await page.request.post(origin + '/__qa/reset', {data: {drop_next: false, reject_next: true, drop_abandon: true}});
  await page.reload();
  await page.getByRole('textbox').fill('Immutable rejection recovery');
  await page.getByRole('button', {name: 'Run research + simulate + forecast →'}).click();
  await page.getByText('Fixture rejected immutable parameters', {exact: true}).waitFor();
  await page.getByRole('button', {name: 'Discard unsubmitted launch', exact: true}).click();
  await page.getByRole('alertdialog').waitFor();
  const focused = await page.getByRole('button', {name: 'Check and discard'}).evaluate(el => el === document.activeElement);
  if (!focused) throw new Error('Discard confirmation has no focused action');
  await page.getByRole('button', {name: 'Check and discard'}).click();
  await page.getByText('Network Error', {exact: true}).waitFor();
  await page.reload();
  await page.getByText('This request was retired before launch. Choose New to edit the inputs.').waitFor();
  await page.getByRole('button', {name: 'New', exact: true}).click();
  await page.getByRole('textbox').fill('Corrected after retirement');
  await page.getByRole('button', {name: 'Run research + simulate + forecast →'}).click();
  await page.getByRole('button', {name: 'Copy pipeline id'}).waitFor();
  const retireResult = await (await page.request.get(origin + '/__qa')).json();
  if (Object.values(retireResult.records).filter(x => x.pipeline_id).length !== 1) throw new Error('Retirement created extra run');
  await clearFixtureStorage();
  await page.request.post(origin + '/__qa/reset', {data: {drop_next: false, launch_status: 'failed'}});
  await page.reload();
  await page.getByRole('textbox').fill('Interrupted admission');
  await page.getByRole('button', {name: 'Run research + simulate + forecast →'}).click();
  await page.getByRole('button', {name: 'Open saved run', exact: true}).waitFor();
  await page.getByRole('button', {name: 'Open saved run', exact: true}).click();
  await page.getByRole('button', {name: 'Copy pipeline id'}).waitFor();
  await page.getByRole('button', {name: '＋ New', exact: true}).click();
  await page.getByRole('alertdialog').waitFor();
  const dialogText = await page.getByRole('alertdialog').innerText();
  if (!dialogText.includes('pipe_qa1')) throw new Error('Uncertain New omitted previous identity');
  await page.screenshot({path: 'output/playwright/astra-launch-uncertain-new.png', animations: 'disabled'});
  if (faults.length) throw new Error(JSON.stringify(faults));
  return {lost_response_get_recovery: true, post_count_before_reload: 1, post_count_after_reload: 1, cross_tab_shared_identity: true, explicit_new_key: true, stale_tab_blocked: true, final_post_count: 2, mobile_overflow: false, rejected_payload_retirement: true, lost_abandon_response_get_recovery: true, interrupted_saved_run_open: true, uncertain_new_confirmation: true, confirmation_focus: true, page_errors: faults};
}
